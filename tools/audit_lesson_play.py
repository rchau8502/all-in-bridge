"""Offline exact DDS audit. Does not use the app's heuristic dds.ts.

Compile shared sources and export getLessons('en') to JSON, then run:
  DDS_LIBRARY_PATH=/path/to/dds.dll python tools/audit_lesson_play.py lessons.json

The DDS 2.9.0 Windows library is available from its author's distribution:
https://privat.bahnhof.se/wb758135/bridge/dds290-dll.zip
No solver binary or network dependency is needed by the app or ordinary tests.
"""
import ctypes as c
import json
import os
from pathlib import Path
import sys

class Deal(c.Structure):
    _fields_ = [('trump', c.c_int), ('first', c.c_int), ('suits', c.c_int * 3),
                ('ranks', c.c_int * 3), ('hands', (c.c_uint * 4) * 4)]

class Future(c.Structure):
    _fields_ = [('nodes', c.c_int), ('cards', c.c_int), ('suit', c.c_int * 13),
                ('rank', c.c_int * 13), ('equals', c.c_int * 13), ('score', c.c_int * 13)]

SEATS, SUITS, RANKS = 'NESW', 'SHDC', '23456789TJQKA'

def label(card):
    return RANKS[card['rank'] - 2] + card['suit']

def winner(trick, trump):
    lead = trick[0][1]['suit']
    return max(trick, key=lambda p: (2 if p[1]['suit'] == trump else
                                    1 if p[1]['suit'] == lead else 0, p[1]['rank']))[0]

def main():
    dll = (c.WinDLL if os.name == 'nt' else c.CDLL)(os.environ['DDS_LIBRARY_PATH'])
    dll.SetMaxThreads(1)
    dll.SolveBoard.argtypes = [Deal, c.c_int, c.c_int, c.c_int, c.POINTER(Future), c.c_int]
    lessons = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
    rows = []
    for lesson in lessons:
        actions = [a for step in lesson['steps'] if step['kind'] == 'play' for a in step['script']]
        if not actions:
            continue
        hands = {s: [dict(card) for card in lesson['hands'][s]] for s in SEATS}
        first = SEATS[(SEATS.index(lesson['contract']['declarer']) + 1) % 4]
        trump, trick, trace, won = lesson['contract']['denom'], [], [], [0, 0]
        for index, action in enumerate(actions):
            d = Deal()
            d.trump = SUITS.index(trump) if trump != 'NT' else 4
            d.first = SEATS.index(first)
            for i, (_, card) in enumerate(trick):
                d.suits[i], d.ranks[i] = SUITS.index(card['suit']), card['rank']
            for i, seat in enumerate(SEATS):
                for card in hands[seat]:
                    d.hands[i][SUITS.index(card['suit'])] |= 1 << card['rank']
            future = Future()
            status = dll.SolveBoard(d, -1, 3, 1, c.byref(future), 0)
            if status != 1:
                raise RuntimeError((lesson['id'], index, status))
            scores = {}
            for i in range(future.cards):
                for rank in range(2, 15):
                    if rank == future.rank[i] or future.equals[i] & (1 << rank):
                        scores[RANKS[rank - 2] + SUITS[future.suit[i]]] = future.score[i]
            seat, chosen = action['seat'], action.get('expected', action.get('card'))
            best = max(scores.values())
            trace.append([seat, chosen, best, scores[chosen]])
            if scores[chosen] != best and not (index == 0 and lesson['id'] in ['trump', 'scoring']):
                raise AssertionError((lesson['id'], index, chosen, scores))
            card = next(card for card in hands[seat] if label(card) == chosen)
            hands[seat].remove(card)
            trick.append((seat, card))
            if len(trick) == 4:
                first = winner(trick, trump)
                won[SEATS.index(first) % 2] += 1
                trick = []
        row = {'id': lesson['id'], 'hands': {s: sorted(label(ca) for ca in lesson['hands'][s]) for s in SEATS},
               'contract': lesson['contract'], 'trace': trace, 'won': won}
        rows.append(row)
        print(lesson['id'], len(trace), 'cards', won, 'NS/EW')
    fixture = Path(__file__).resolve().parents[1] / 'shared/lesson-play-audit-data.ts'
    fixture.write_text('/** Generated by tools/audit_lesson_play.py using exact DDS 2.9.0. */\n'
                       'export interface PlayAudit { id: string; hands: Record<string, string[]>; '
                       'contract: { level: number; denom: string; declarer: string; doubled: number }; '
                       'trace: Array<[string, string, number, number]>; won: number[] }\n'
                       'export const PLAY_AUDITS: PlayAudit[] = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')

if __name__ == '__main__':
    main()
